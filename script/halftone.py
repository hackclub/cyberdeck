#!/usr/bin/env python3
"""Generate the halftone tile behind the landing page panels.

    python3 script/halftone.py [settings.json] [out.svg]

Defaults: script/halftone.json and app/assets/images/landing/halftone.svg.
The algorithm and the random generator match the Halftone tuner artifact,
so a settings JSON copied from it reproduces the same tile here.
"""
import json, math, sys

def rng(seed):
    # mulberry32, in 32-bit unsigned arithmetic, same stream as the tuner.
    a = seed & 0xFFFFFFFF
    def imul(x, y): return (x * y) & 0xFFFFFFFF
    def r():
        nonlocal a
        a = (a + 0x6D2B79F5) & 0xFFFFFFFF
        t = imul(a ^ (a >> 15), (1 | a) & 0xFFFFFFFF)
        t = ((t + imul(t ^ (t >> 7), (61 | t) & 0xFFFFFFFF)) ^ t) & 0xFFFFFFFF
        return ((t ^ (t >> 14)) & 0xFFFFFFFF) / 4294967296
    return r

def f(n):
    s = f"{n:.2f}"
    return s.rstrip("0").rstrip(".") if "." in s else s

def generate(s):
    W, H, P = s["width"], s["height"], s["pitch"]
    cols, rows = W // P, H // P
    rand = rng(s["seed"])
    ph = [rand() * math.pi * 2 for _ in range(3)]
    spiky = [rand() ** s["tongueSharp"] for _ in range(cols)]
    reach = []
    for c in range(cols):
        u = 2 * math.pi * c / cols
        smooth = (0.5 + 0.44 * math.sin(u * s["waveFreq"] + ph[0])
                  + 0.32 * math.sin(u * s["waveFreq"] * 2.5 + ph[1])
                  + 0.24 * math.sin(u * s["waveFreq"] * 4.5 + ph[2]))
        tongue = (1 - s["tongueWidth"]) * spiky[c] + s["tongueWidth"] * 0.5 * (spiky[(c - 1) % cols] + spiky[(c + 1) % cols])
        reach.append(s["reachMin"] + s["waveAmp"] * smooth + s["tongueAmp"] * tongue)
    wsum = (s["wCircle"] + s["wSquare"] + s["wTriangle"]) or 1
    out = []
    for r in range(rows):
        cy = r * P + P / 2
        for c in range(cols):
            t = min(1.0, (cy / H) * reach[c])
            size = s["sizeMin"] + (s["sizeMax"] - s["sizeMin"]) * t ** s["sizeExp"]
            keep = s["keepMin"] + (s["keepMax"] - s["keepMin"]) * t ** s["keepExp"]
            if rand() > keep: continue
            cx = c * P + P / 2 + (rand() - 0.5) * P * s["jitterX"]
            y = cy + (rand() - 0.5) * P * s["jitterY"] * (1 - t)
            sz = size * (1 - s["sizeVar"] / 2 + s["sizeVar"] * rand())
            if sz <= 0.05: continue
            where = 1 - t if s["rotWhere"] == "top" else t if s["rotWhere"] == "bottom" else 1
            angle = s["rotMax"] * where ** s["rotExp"] * (rand() * 2 - 1)
            op = "" if s["opacityTop"] >= 1 else f' fill-opacity="{f(s["opacityTop"] + (1 - s["opacityTop"]) * t)}"'
            k = rand() * wsum
            rot = f' transform="rotate({f(angle)} {f(cx)} {f(y)})"' if abs(angle) > 0.5 else ""
            if k < s["wCircle"]:
                out.append(f'<circle cx="{f(cx)}" cy="{f(y)}" r="{f(sz)}"{op}/>')
            elif k < s["wCircle"] + s["wSquare"]:
                out.append(f'<rect x="{f(cx - sz)}" y="{f(y - sz)}" width="{f(2 * sz)}" height="{f(2 * sz)}"{op}{rot}/>')
            else:
                out.append(f'<path d="M{f(cx)} {f(y - sz * 1.1)}L{f(cx + sz * 1.15)} {f(y + sz * 0.9)}H{f(cx - sz * 1.15)}Z"{op}{rot}/>')
    head = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" '
            f'fill="{s["fill"]}" fill-opacity="{f(s["opacity"])}">\n'
            f'<!-- Halftone for the landing panels. Generated by script/halftone.py from script/halftone.json. Do not edit by hand. -->\n')
    return head + "\n".join(out) + "\n</svg>\n", len(out)

if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else "script/halftone.json"
    dst = sys.argv[2] if len(sys.argv) > 2 else "app/assets/images/landing/halftone.svg"
    settings = json.load(open(src))
    svg, n = generate(settings)
    open(dst, "w").write(svg)
    print(f"{n} dots, {len(svg) / 1024:.1f} KB, {dst}")
